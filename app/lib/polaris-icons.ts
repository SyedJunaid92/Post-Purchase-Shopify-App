/** Maps legacy short icon ids saved before the full Polaris list. */
export const LEGACY_TRIAL_FEATURE_ICON_ALIASES: Record<string, PolarisIconType> = {
  shield: "shield-check-mark",
  chart: "chart-line",
  lock: "lock",
  star: "star",
};

export function normalizeTrialFeatureIcon(
  icon: string | null | undefined,
): PolarisIconType | null {
  if (!icon?.trim()) return null;
  const value = icon.trim();
  const aliased = LEGACY_TRIAL_FEATURE_ICON_ALIASES[value.toLowerCase()] ?? value;
  return isPolarisIconType(aliased) ? aliased : null;
}

export function resolveTrialFeatureIcon(
  icon: string | null | undefined,
): PolarisIconType | null {
  return normalizeTrialFeatureIcon(icon);
}
