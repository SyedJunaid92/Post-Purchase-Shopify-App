export type PolarisIconType = (typeof POLARIS_ICON_TYPES)[number];

const POLARIS_ICON_TYPE_SET = new Set<string>(POLARIS_ICON_TYPES);

export function isPolarisIconType(value: string | null | undefined): value is PolarisIconType {
  return Boolean(value && POLARIS_ICON_TYPE_SET.has(value));
}

export function formatPolarisIconLabel(icon: string): string {
  return icon
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

